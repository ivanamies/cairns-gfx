// String interning: a name is a byte slice into a persistent BumpArena
// (Engine::prefab_arena_). Pointer-free POD, so records stay raw-hashable
// and under the block cap.
using NameRef = cairns::ArenaSlice<char>;

// Fail loud on prefab-arena overflow: ArenaSlice::Alloc returns a null slice
// when the BumpArena is full, and the fill loop would then write through a
// nullptr. Abort with a clear "raise kPrefabArenaBytes" message instead.
template <typename T>
inline cairns::ArenaSlice<T> AllocSliceOrDie(cairns::BumpArena& arena,
                                             uint32_t n, const char* what) {
    cairns::ArenaSlice<T> s = cairns::ArenaSlice<T>::Alloc(arena, n);
    if (n > 0 && s.IsNull()) {
        std::fprintf(stderr,
                     "[PREFAB-ARENA] overflow: %u x %s -- raise kPrefabArenaBytes\n",
                     n, what);
        std::abort();
    }
    return s;
}

inline NameRef InternName(cairns::BumpArena& arena, std::string_view s) {
    NameRef r = AllocSliceOrDie<char>(arena, static_cast<uint32_t>(s.size()),
                                      "name byte");
    if (!r.IsNull()) {
        std::memcpy(r.data(arena), s.data(), s.size());
    }
    return r;
}

inline std::string_view ResolveName(cairns::BumpArena& arena, NameRef n) {
    return n.empty() ? std::string_view{}
                     : std::string_view(n.data(arena), n.count);
}

