// Per-vertex joint + weight payload for skinned meshes. 32 B; only populated
// for meshes whose primitives carry JOINTS_0 / WEIGHTS_0. Unskinned meshes
// leave Mesh::Cold::cpuSkinAttrs empty so the static crowd pays 0 B/vert.
struct SkinVertex {
    glm::uvec4 joints = glm::uvec4(0);
    glm::vec4  weights = glm::vec4(1.0f, 0.0f, 0.0f, 0.0f);
};

// GPU-side packed skin vertex. 8 B (4x u8 joints + 4x u8 unorm weights).
// Largest-remainder renorm during pack guarantees the weights sum to exactly
// 255 post-quantization so seams don't crack.
struct PackedSkinVertex {
    uint32_t joints_packed = 0;   // u8 j0 | u8 j1 | u8 j2 | u8 j3 (LSB first)
    uint32_t weights_packed = 0;  // u8 w0 | u8 w1 | u8 w2 | u8 w3
};

inline PackedSkinVertex PackSkinVertex(const SkinVertex& v) {
    PackedSkinVertex p;
    p.joints_packed =
        (v.joints.x & 0xFFu) |
        ((v.joints.y & 0xFFu) << 8) |
        ((v.joints.z & 0xFFu) << 16) |
        ((v.joints.w & 0xFFu) << 24);
    // u8 quantization with largest-remainder renorm. Compute floor(w*255)
    // per channel, distribute the deficit to the channels with the largest
    // fractional remainders.
    const float wsum =
        v.weights.x + v.weights.y + v.weights.z + v.weights.w;
    const float inv = (wsum > 1e-6f) ? (1.0f / wsum) : 0.0f;
    const float ns[4] = {
        v.weights.x * inv, v.weights.y * inv,
        v.weights.z * inv, v.weights.w * inv,
    };
    const float scaled[4] = {
        ns[0] * 255.0f, ns[1] * 255.0f, ns[2] * 255.0f, ns[3] * 255.0f,
    };
    uint32_t base[4] = {
        static_cast<uint32_t>(scaled[0]),
        static_cast<uint32_t>(scaled[1]),
        static_cast<uint32_t>(scaled[2]),
        static_cast<uint32_t>(scaled[3]),
    };
    uint32_t total = base[0] + base[1] + base[2] + base[3];
    int32_t deficit = 255 - static_cast<int32_t>(total);
    // Give 1 LSB to the channels with the largest remainders, in order.
    for (int32_t k = 0; k < deficit && k < 4; ++k) {
        float best_rem = -1.0f;
        int best_idx = 0;
        for (int i = 0; i < 4; ++i) {
            const float rem = scaled[i] - static_cast<float>(base[i]);
            // Skip channels already bumped this round.
            if (((base[i] + 1u) > 255u) || rem <= best_rem) {
                continue;
            }
            best_rem = rem;
            best_idx = i;
        }
        if (base[best_idx] < 255u) {
            base[best_idx]++;
        }
    }
    p.weights_packed =
        (base[0] & 0xFFu) |
        ((base[1] & 0xFFu) << 8) |
        ((base[2] & 0xFFu) << 16) |
        ((base[3] & 0xFFu) << 24);
    return p;
}

struct Primitive {
    uint32_t firstIndex = 0;
    uint32_t indexCount = 0;
    int32_t  vertexOffset = 0; // Base Vertex (added to index value)
    uint32_t materialIndex = 0;
};

// Aaltonen Hot/Cold split. Pooled via cairns::ResourceManager<Mesh> on
// Engine; MeshId is Handle<Mesh>. Mesh data is engine-owned -- prefabs hold
// only handles, so multiple prefabs can share one loaded GLB.
struct Mesh {
    struct Hot {
        // Read on every draw of this mesh.
        rhi::Handle<rhi::Buffer> posHandle;
        rhi::Handle<rhi::Buffer> attrHandle; // shared vertex-stream attrs
        rhi::Handle<rhi::Buffer> indexHandle;
        std::vector<Primitive> primitives;
        // Snapshot of LoadPrefabsGpu's running_vert. Skinned draws subtract
        // this to get the mesh-local baseVertex: vkCmdDrawIndexed has ONE
        // vertexOffset serving stream 0 + stream 1 globally, but the skinned
        // stream-0 binds a per-actor slice of skin_output_pool_ that is
        // mesh-local indexed.
        uint32_t global_base_vertex = 0;
        // Base index into the shared skin-attr SSBO for this mesh's slice
        // (0 for unskinned meshes, which contribute nothing).
        uint32_t skin_attr_base_vertex = 0;
        // Snapshot of cpuPositions.size() taken at upload, before
        // CleanupTmps clears the CPU temporaries. Sizes the skin dispatch +
        // the skin_output_pool_ slice (cpuPositions is gone by then).
        uint32_t vert_count = 0;
        // Bind-pose AABB in mesh-local space, computed at load over
        // cpuPositions; persists past CleanupTmps. Per-actor frustum cull
        // transforms it by the actor's world xform, pads 1.5x for animation
        // motion, and tests the camera's 6 planes (skip anim_eval + skin
        // dispatch when fully outside).
        glm::vec3 bind_aabb_min = glm::vec3(0.0f);
        glm::vec3 bind_aabb_max = glm::vec3(0.0f);
        // Per-skinned-mesh alias of the shared attr region pre-offset by
        // global_base_vertex * sizeof(VertexAttribute). Stream 1 binds this
        // for skinned draws; mesh-local vertex_offset then indexes
        // correctly. Null for unskinned meshes (they use attrHandle).
        rhi::Handle<rhi::Buffer> attr_skinned_alias;
        // Group A descriptor set for this skinned mesh (positions slice +
        // skin-attrs slice), allocated at prefab load via
        // Resources::CreateSkinGroupA. Null on Metal (its compute path binds
        // buffers directly per batch).
        rhi::Handle<rhi::BindGroup> skin_group_a;
        // Index into Engine::per_batch_shared_skin_ identifying which
        // LoadPrefabBatch upload produced this mesh's shared skin-attrs
        // buffer; 0 for unskinned meshes (never read). Group A binding 1
        // resolves the buffer via per_batch_shared_skin_[batch_id] -- the
        // shared-attrs dedup is per batch, not program-wide.
        uint16_t batch_id = 0;
    };
    struct Cold {
        NameRef name;  // Slice into prefab_arena_.
        // CPU load-time temporaries, cleared post-upload by Engine's
        // mesh-pool sweep. Deliberately on malloc, NOT cpu_block_: they peak
        // ~600 MB across the 100-GLB batch (too big for the block) and are
        // transient (empty before any frame, outside the determinism hash).
        std::vector<glm::vec4> cpuPositions;
        std::vector<VertexAttribute> cpuAttrs;
        std::vector<uint32_t> cpuIndices;
        // Per-vertex joint indices + weights aligned with
        // cpuPositions/cpuAttrs (size() == cpuPositions.size() when the mesh
        // is skinned; empty when not).
        std::vector<SkinVertex> cpuSkinAttrs;
    };
};

struct Node {
    // Pointer-free POD: name/children are slices into Engine::prefab_arena_
    // (resolve via the threaded BumpArena), so Node is raw-hashable and
    // lives under the block cap.
    NameRef name;
    glm::mat4 localTransform = glm::mat4(1.0f);
    glm::mat4 globalTransform = glm::mat4(1.0f);

    int32_t meshIndex = -1; // Index into Scene.meshes
    int32_t skinIndex = -1; // Index into Prefab::Cold::skins; -1 = no skin.
    cairns::ArenaSlice<int32_t> children;
};

// Per-glTF skin (joint set + inverse binds). Joints reference
// Prefab::Cold::nodes by index; inverseBinds is one mat4 per joint in the
// same order. skeletonRoot is the glTF "skeleton" hint (-1 if absent; unused
// by the runtime — joint world matrices come from the node walk).
struct Skin {
    // Slices into Engine::prefab_arena_.
    cairns::ArenaSlice<int32_t> jointNodes;
    cairns::ArenaSlice<glm::mat4> inverseBinds;
    int32_t skeletonRoot = -1;
};

// Animation primitives. AnimationSampler stores the keyframe array for one
// channel (times + values + interpolation mode). Channel binds a sampler to
// a (node, path) target. Clip groups them under one name + duration.
enum class AnimationInterpolation : uint8_t {
    kStep,
    kLinear,
    kCubicSpline,
};

enum class AnimationPath : uint8_t {
    kTranslation,
    kRotation,
    kScale,
    kWeights,
};

struct AnimationSampler {
    // Keyframes are NOT read at parse. Parse stores the glTF accessor
    // handles + the output's value shape; only the SELECTED walk clip's
    // samplers are read (into the flat gpu_times/gpu_values) at flatten
    // time, so unused clips cost zero keyframe allocations. value_kind:
    // 0=Vec3 (T/S, widen w=0), 1=Vec4 (R quat), 2=Scalar (weights, .x).
    uint32_t input_accessor = 0;
    uint32_t output_accessor = 0;
    uint8_t value_kind = 0;
    AnimationInterpolation interp = AnimationInterpolation::kLinear;
};

struct AnimationChannel {
    int32_t samplerIndex = -1;
    int32_t nodeIndex = -1;
    AnimationPath path = AnimationPath::kTranslation;
};

struct Clip {
    // Name + sampler/channel arrays are slices into prefab_arena_.
    NameRef name;
    cairns::ArenaSlice<AnimationSampler> samplers;
    cairns::ArenaSlice<AnimationChannel> channels;
    float duration = 0.0f;
};

